'use client';

import React, { useState } from 'react';
import { useVideoChat } from '@/contexts/VideoChatContext';
import { VideoGrid } from './VideoGrid';
import { ParticipantList } from './ParticipantList';
import { CallControls } from './CallControls';
import { JoinRoom } from './JoinRoom';

export function VideoChat() {
  const { roomState } = useVideoChat();
  const [showParticipants, setShowParticipants] = useState(false);

  if (!roomState.isConnected) {
    return <JoinRoom />;
  }

  return (
    <div className="h-screen flex flex-col bg-gray-900">
      {/* Header */}
      <header className="bg-gray-800 border-b border-gray-700 px-4 py-3">
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 bg-blue-600 rounded-full flex items-center justify-center">
              <VideoIcon className="w-5 h-5 text-white" />
            </div>
            <div>
              <h1 className="text-white font-semibold">Video Chat</h1>
              <p className="text-gray-400 text-sm">Room: {roomState.roomId}</p>
            </div>
          </div>
          
          <div className="flex items-center gap-2">
            <button
              onClick={() => setShowParticipants(!showParticipants)}
              className={`p-2 rounded-lg transition-colors ${
                showParticipants 
                  ? 'bg-blue-600 text-white' 
                  : 'bg-gray-700 text-gray-300 hover:bg-gray-600'
              }`}
              title="Toggle participants panel"
            >
              <UsersIcon className="w-5 h-5" />
            </button>
            
            <CopyRoomIdButton roomId={roomState.roomId} />
          </div>
        </div>
      </header>

      {/* Main content */}
      <div className="flex-1 flex overflow-hidden">
        <VideoGrid />
        
        {showParticipants && (
          <div className="p-4 border-l border-gray-700">
            <ParticipantList />
          </div>
        )}
      </div>

      {/* Call controls */}
      <CallControls />
    </div>
  );
}

function CopyRoomIdButton({ roomId }: { roomId: string }) {
  const [copied, setCopied] = useState(false);

  const handleCopy = async () => {
    await navigator.clipboard.writeText(roomId);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <button
      onClick={handleCopy}
      className="p-2 rounded-lg bg-gray-700 text-gray-300 hover:bg-gray-600 transition-colors"
      title="Copy room ID"
    >
      {copied ? (
        <CheckIcon className="w-5 h-5 text-green-400" />
      ) : (
        <CopyIcon className="w-5 h-5" />
      )}
    </button>
  );
}

